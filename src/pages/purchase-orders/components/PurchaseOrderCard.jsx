import React from 'react';
import Icon from '../../../components/AppIcon';
import Button from '../../../components/ui/Button';
import { useCurrency } from '../../../contexts/CurrencyContext';

const STATUS_CONFIG = {
  draft: { label: 'Borrador', color: 'bg-gray-100 text-gray-700', icon: 'FileText' },
  sent: { label: 'Enviado', color: 'bg-blue-100 text-blue-700', icon: 'Send' },
  in_process: { label: 'En proceso', color: 'bg-yellow-100 text-yellow-700', icon: 'Clock' },
  received_partial: { label: 'Recibido parcial', color: 'bg-orange-100 text-orange-700', icon: 'PackageOpen' },
  received_complete: { label: 'Recibido completo', color: 'bg-green-100 text-green-700', icon: 'PackageCheck' },
  paid: { label: 'Pagado', color: 'bg-emerald-100 text-emerald-700', icon: 'CheckCircle' },
  pending_payment: { label: 'Pendiente de pago', color: 'bg-red-100 text-red-700', icon: 'AlertCircle' },
  cancelled: { label: 'Cancelado', color: 'bg-gray-100 text-gray-500', icon: 'XCircle' }
};

const PurchaseOrderCard = ({ order, onUpdateStatus, onPrint, onView, onReceive }) => {
  const { formatPrice } = useCurrency();
  const status = STATUS_CONFIG?.[order?.status] || STATUS_CONFIG?.draft;
  const isAutoGenerated = order?.is_auto_generated;
  const canReceive = ['in_process', 'received_partial']?.includes(order?.status);

  const nextStatuses = {
    draft: ['sent', 'cancelled'],
    sent: ['in_process', 'cancelled'],
    in_process: [],
    received_partial: [],
    received_complete: ['paid', 'pending_payment'],
    pending_payment: ['paid'],
    paid: [],
    cancelled: []
  };

  return (
    <div className={`bg-card rounded-xl border p-5 hover:shadow-md transition-shadow ${
      isAutoGenerated ? 'border-orange-300 bg-orange-50/30' : 'border-border'
    }`}>
      <div className="flex items-start justify-between mb-3">
        <div>
          <div className="flex items-center gap-2">
            <h3 className="font-semibold text-foreground">{order?.order_number}</h3>
            {isAutoGenerated && (
              <span className="px-1.5 py-0.5 bg-orange-100 text-orange-700 text-xs rounded font-medium flex items-center gap-1">
                <Icon name="Zap" size={10} /> Auto
              </span>
            )}
            {order?.status === 'in_process' && (
              <span title="Pendiente de recepción">
                <Icon name="Clock" size={13} className="text-yellow-500" />
              </span>
            )}
          </div>
          <p className="text-xs text-muted-foreground mt-0.5">{order?.supplier_name || 'Sin proveedor'}</p>
        </div>
        <span className={`px-2 py-1 rounded-full text-xs font-medium flex items-center gap-1 ${status?.color}`}>
          <Icon name={status?.icon} size={12} />
          {status?.label}
        </span>
      </div>
      <div className="grid grid-cols-2 gap-2 mb-4">
        <div className="bg-muted/50 rounded-lg p-2">
          <p className="text-xs text-muted-foreground">Total</p>
          <p className="text-sm font-bold text-foreground">{formatPrice(order?.total_amount || 0)}</p>
        </div>
        <div className="bg-muted/50 rounded-lg p-2">
          <p className="text-xs text-muted-foreground">Productos</p>
          <p className="text-sm font-bold text-foreground">{order?.items_count || 0} ítems</p>
        </div>
        <div className="bg-muted/50 rounded-lg p-2">
          <p className="text-xs text-muted-foreground">Creado</p>
          <p className="text-xs font-medium text-foreground">{new Date(order?.created_at)?.toLocaleDateString('es-MX')}</p>
        </div>
        <div className="bg-muted/50 rounded-lg p-2">
          <p className="text-xs text-muted-foreground">Entrega esperada</p>
          <p className="text-xs font-medium text-foreground">
            {order?.expected_delivery_date ? new Date(order?.expected_delivery_date)?.toLocaleDateString('es-MX') : '—'}
          </p>
        </div>
      </div>
      {/* Status Actions */}
      {nextStatuses?.[order?.status]?.length > 0 && (
        <div className="mb-3">
          <p className="text-xs text-muted-foreground mb-1">Cambiar estado:</p>
          <div className="flex flex-wrap gap-1">
            {nextStatuses?.[order?.status]?.map(nextStatus => (
              <button
                key={nextStatus}
                onClick={() => onUpdateStatus?.(order?.id, nextStatus)}
                className={`px-2 py-1 rounded text-xs font-medium transition-colors ${STATUS_CONFIG?.[nextStatus]?.color} hover:opacity-80`}
              >
                {STATUS_CONFIG?.[nextStatus]?.label}
              </button>
            ))}
          </div>
        </div>
      )}
      {/* Receive button for in_process and received_partial */}
      {canReceive && (
        <button
          onClick={() => onReceive?.(order?.id)}
          className="w-full mb-3 flex items-center justify-center gap-1.5 px-3 py-2 bg-primary text-primary-foreground rounded-lg text-sm font-medium hover:bg-primary/90 transition-colors"
        >
          <Icon name="PackageCheck" size={15} />
          {order?.status === 'received_partial' ? 'Completar recepción' : 'Recibir pedido'}
        </button>
      )}
      <div className="flex gap-2">
        <Button variant="outline" size="sm" onClick={() => onView?.(order)} iconName="Eye" iconPosition="left" className="flex-1">Ver detalle</Button>
        <Button variant="outline" size="sm" onClick={() => onPrint?.(order)} iconName="Printer" iconSize={14} />
      </div>
    </div>
  );
};

export default PurchaseOrderCard;
